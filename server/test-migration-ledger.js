'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const Database=require('better-sqlite3'),express=require('express');
const {createMigrationRouter}=require('./migration_routes');
const {readMigrationLedger}=require('./migration_ledger');
test('admin ledger retains all pages, exact totals and wallet isolation without signed data',async t=>{
  const db=new Database(':memory:');t.after(()=>db.close());
  const migration=createMigrationRouter({db,chain:{},autoStart:false,env:{ADMIN_KEY:'test-secret'},logger:()=>{}});
  const wallet='1'.repeat(32),other='2'.repeat(32),insert=db.prepare('INSERT INTO migration_requests VALUES(?,?,?,?,?,?,?)');
  const payload={inputUnits:'4000000000',outputUnits:'4000000',feeLamports:'20000000',targetDecimals:6,targetToken:'0x'+'1'.repeat(40),destination:'0x'+'2'.repeat(40),raw:'PRIVATE_SIGNED_BYTES',token:'PRIVATE_TOKEN'};
  for(let i=0;i<201;i++) insert.run('q'+i,wallet,'i'+i,'quoted',JSON.stringify(payload),i+1,i+1);
  insert.run('paid',other,'paid','paid',JSON.stringify({...payload,depositedAt:1700000000000,paidAt:1700000001000}),999,999);
  insert.run('pending',other,'pending','deposit_signed',JSON.stringify(payload),1000,1000);
  const data=readMigrationLedger(db);
  assert.equal(data.summary.requests,203);assert.equal(data.pages,5);assert.equal(data.requests.length,50);
  assert.equal(data.summary.confirmedInputUnits,'4000000000');assert.equal(data.summary.confirmedFeeLamports,'20000000');
  assert.equal(data.summary.paidRequests,1);assert.equal(data.summary.payouts[0].units,'4000000');
  assert.equal(readMigrationLedger(db,{wallet}).summary.confirmedDeposits,0);
  assert.equal(readMigrationLedger(db,{page:5}).requests.length,3);
  assert.doesNotMatch(JSON.stringify(data),/PRIVATE/);
  assert.throws(()=>readMigrationLedger(db,{wallet:"' OR 1=1"}));
  const app=express();app.use('/api/migration',migration.router);
  const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
  t.after(()=>{server.closeAllConnections();server.close();});const url='http://127.0.0.1:'+server.address().port;
  assert.equal((await fetch(url+'/api/migration/admin/ledger')).status,403);
  assert.equal((await fetch(url+'/api/migration/admin/ledger?page=-1',{headers:{'x-admin-key':'test-secret'}})).status,400);
  const response=await fetch(url+'/api/migration/admin/ledger?wallet='+other,{headers:{'x-admin-key':'test-secret'}});
  assert.equal(response.status,200);assert.equal((await response.json()).summary.requests,2);
});
